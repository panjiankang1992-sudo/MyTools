node "$TSC_BIN" "$TEST_DIR/RemoteBookDownloadPolicy.ts" --target ES2020 --module commonjs \
  --outDir "$TEST_DIR/output" --skipLibCheck
node "$APP_DIR/tests/remote_book_download_policy_test.cjs" "$TEST_DIR/output/RemoteBookDownloadPolicy.js"

grep -Fq 'this.remoteDownloadPolicy.url(url)' "$LOADER"
