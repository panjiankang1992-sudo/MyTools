grep -Fq "'远程PDF', 'pdf'" "$LOADER"
grep -Fq "'远程MOBI', 'mobi'" "$LOADER"
grep -Fq 'request.requestInStream(safeUrl' "$LOADER"
grep -Fq 'if (!completed) this.removePartialDownload(path)' "$LOADER"
