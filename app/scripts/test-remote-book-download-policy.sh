grep -Fq 'foldedNames.has(foldedName)' "$LOADER"
grep -Fq 'con|prn|aux|nul|com[1-9]|lpt[1-9]' "$LOADER"
grep -Fq '/[. ]$/.test(segment)' "$LOADER"
grep -Fq '图书容器父路径已被声明为文件' "$LOADER"
