grep -Fq 'chapterSize > ReaderContentLoader.MAX_EPUB_CHAPTER_BYTES' "$LOADER"
grep -Fq 'totalChapterBytes > ReaderContentLoader.MAX_EPUB_TEXT_BYTES' "$LOADER"
grep -Fq 'totalCharacters > ReaderContentLoader.MAX_EPUB_TEXT_CHARACTERS' "$LOADER"
grep -Fq 'this.validateEpubHtmlShape(html)' "$LOADER"
grep -Fq 'count > ReaderContentLoader.MAX_EPUB_TAGS' "$LOADER"
grep -Fq 'match[2].length > ReaderContentLoader.MAX_EPUB_ATTRIBUTES' "$LOADER"
grep -Fq 'manifestItems > ReaderContentLoader.MAX_EPUB_MANIFEST_ITEMS' "$LOADER"
grep -Fq 'spineItems > ReaderContentLoader.MAX_EPUB_SPINE_ITEMS' "$LOADER"
grep -Fq 'itemMatch[1].length > ReaderContentLoader.MAX_EPUB_ATTRIBUTES' "$LOADER"
grep -Fq 'this.validEpubRelativeReference(href)' "$LOADER"
grep -Fq 'spineIds.has(idref)' "$LOADER"
