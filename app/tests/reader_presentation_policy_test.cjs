const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('/Applications/DevEco-Studio.app/Contents/tools/hvigor/hvigor/node_modules/typescript');
const source = fs.readFileSync('app/entry/src/main/ets/features/reader/ReaderPresentationPolicy.ets','utf8');
const box = { exports: {} };
vm.runInNewContext(ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,box);
const p = new box.exports.ReaderPresentationPolicy();
for (const value of ['{"trackId":1,"url":"https://example.test"}', '{"trackId":1,', 'https://example.test/api', '  ']) assert.equal(p.chapterLabel(value), '');
for (const value of ['第十二章', 'JSON 与 HTTP 入门', '访问 https://example.test 的方法', '数组 [1, 2] 的使用']) assert.equal(p.chapterLabel(value), value);
assert.equal(p.chapterLabel('  第十二章  '), '第十二章');
const page = fs.readFileSync('app/entry/src/main/ets/pages/Index.ets','utf8');
const methods = ['DetailChapterLabel','OpenFailedBookDetail'].map(name => page.match(new RegExp(`^  private ${name}\\([\\s\\S]*?^  }`,'m'))[0]).join('\n');
const context = { ReaderPresentationPolicy: box.exports.ReaderPresentationPolicy };
vm.createContext(context);
vm.runInContext(ts.transpileModule(`class Reader {${methods}} globalThis.Reader=Reader;`, {compilerOptions:{target:ts.ScriptTarget.ES2020}}).outputText,context);
const r = new context.Reader();
r.detailLastChapter='{"trackId":1}';r.detailCatalog={chapters:[{title:'可信章节'}]};
assert.equal(r.DetailChapterLabel(),'可信章节');
r.detailCatalog=undefined;assert.equal(r.DetailChapterLabel(),'');
const events=[];r.readerOpenFailed=true;r.currentBook={id:'a'};
r.CloseReader=skip=>{assert.equal(skip,true);events.push('close');r.currentBook=undefined;};
r.OpenBookDetail=b=>{assert.equal(b.id,'a');events.push('detail');};
r.OpenFailedBookDetail();assert.deepEqual(events,['close','detail']);
console.log('Metadata sanitization, technical titles, catalog fallback and failed-open detail recovery passed');
