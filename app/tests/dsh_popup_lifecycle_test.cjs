const assert = require('node:assert/strict');
const { DshPopupLifecycle } = require(process.argv[2]);
let rejected = 0, bound = 0;
const cancelled = new DshPopupLifecycle(() => rejected++);
cancelled.close();
cancelled.close();
assert.equal(rejected, 1, 'Pending browser request must be released exactly once');
assert.equal(cancelled.attach(() => bound++), false, 'Late mount must not bind a cancelled request');
assert.equal(cancelled.forward(), false);
assert.equal(bound, 0);
const connected = new DshPopupLifecycle(() => rejected++);
assert.equal(connected.forward(), false, 'Cannot hand off before child controller is bound');
assert.equal(connected.attach(() => bound++), true);
assert.equal(connected.attach(() => bound++), false);
assert.equal(connected.forward(), true);
assert.equal(connected.forward(), false, 'Repeated navigation must not launch another browser');
connected.close();
assert.equal(rejected, 1, 'Bound controllers must not receive a second null binding');
assert.equal(connected.forward(), false);
const retry = new DshPopupLifecycle(() => rejected++);
assert.equal(retry.attach(() => bound++), true);
connected.close();
assert.equal(retry.forward(), true, 'Closing an old attempt must not poison a new login');
retry.close();
let recoveryRejected = 0;
const failedMount = new DshPopupLifecycle(() => recoveryRejected++);
assert.throws(() => failedMount.attach(() => { throw new Error('Renderer unavailable'); }));
failedMount.close();
assert.equal(recoveryRejected, 1, 'Failed binding must still release the pending request');
console.log('PASS: cancel-before-mount, exactly-once binding, duplicate handoff, late callback, retry isolation');
