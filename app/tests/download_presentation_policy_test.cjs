const assert = require('node:assert/strict');
const { DownloadPresentationPolicy: P } = require(process.argv[2]);
assert.equal(P.size(0), '0 B');
assert.equal(P.size(1024), '1.00 KB');
assert.equal(P.size(100 * 1024 ** 2), '100.00 MB');
for (const n of [undefined, null, -1, NaN, Infinity, 1.5, '1024']) assert.equal(P.size(n), '');
assert.deepEqual(P.files(undefined), []);
assert.deepEqual(P.files(null), []);
const files = P.files([null, { fileName: ' demo.MP4 ', sizeBytes: 1024, storageUri: ' storage://image/demo.mp4 ', tagStatus: 'FAILED', tags: [null, { name: ' city ' }, { name: 'city' }, {}, { name: 'night' }] }, { fileName: null, tags: undefined }]);
assert.equal(files.length, 2);
assert.equal(files[0].kind, 'video');
assert.deepEqual(files[0].tags, ['city', 'night']);
assert.equal(files[1].size, '');
assert.equal(files[1].name, '');
assert.deepEqual(files[1].tags, []);
assert.equal(P.state('FAILED', files), 'partial');
assert.equal(P.state('FAILED', []), 'failed');
assert.equal(P.state('SUCCEEDED', files), 'attention');
assert.equal(P.state('SUCCEEDED', []), 'done');
assert.equal(P.state('FUTURE_STATE', files), 'unknown');
assert.equal(P.state('CANCELLED', files), 'cancelled');
assert.equal(P.state('EXPIRED', []), 'expired');
assert.equal(P.state('NO_MATCH', []), 'no_match');
for (const state of ['ACCEPTED', 'PLANNING', 'RUNNING', 'UPLOADING', 'CANCELLING']) assert.equal(P.state(state, []), 'active');
for (const [n, expected] of [[undefined, 0], [NaN, 0], [Infinity, 0], [-20, 0], [101, 100], [45.7, 46]]) assert.equal(P.progress(n), expected);
for (const [name, kind] of [['a.jpg', 'image'], ['a.MP3', 'audio'], ['a.pdf', 'file']]) assert.equal(P.kind(name), kind);
console.log('PASS presentation: status truthfulness, legacy fields, tags, sizes, media types and bounded progress');
