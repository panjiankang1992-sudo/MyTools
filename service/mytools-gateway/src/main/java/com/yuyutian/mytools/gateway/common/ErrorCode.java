package com.yuyutian.mytools.gateway.common;
/** 图片与视频领域透传到客户端的稳定错误码。 */
public enum ErrorCode {
    IMAGE_002, IMAGE_003, IMAGE_004, IMAGE_005, IMAGE_007,
    /** 输入无效：参数、素材大小或标识不合法。 */
    VIDEO_001,
    /** 能力不支持：当前模式未通过验收，或上游拒绝该媒体类型。 */
    VIDEO_002,
    /** 资源不足：上游以 503 拒绝本次提交（显存、队列或保存失败）。 */
    VIDEO_003,
    /** 推理失败：任务本身结束为失败，错误码由任务详情返回。 */
    VIDEO_004,
    /** 超时：任务在截止时间内没有产出。 */
    VIDEO_005,
    /** 资产保存失败：成片未能登记，可重试。 */
    VIDEO_006,
    /** 鉴权失败：会话或内部令牌无效。 */
    VIDEO_007,
    /** 幂等冲突：同一幂等键对应了不同的请求内容。 */
    VIDEO_008,
    /** 资源不存在：任务、素材或成片不可见或不属于当前账户。 */
    VIDEO_009,
    /** 服务暂不可用：路由未启用、上游不可达或上游内部错误。 */
    VIDEO_010
}
