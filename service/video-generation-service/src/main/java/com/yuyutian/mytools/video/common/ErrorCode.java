package com.yuyutian.mytools.video.common;
/** 视频业务稳定错误码，用户文案由 App 侧国际化维护。 */
public enum ErrorCode {
 /** 输入无效：参数、素材角色、裁剪或不变量不合法。 */
 VIDEO_001,
 /** 能力不支持：模式、尺寸、帧数或模型尚未通过验收。 */
 VIDEO_002,
 /** 资源不足：显存、内存或磁盘未达到准入门槛。 */
 VIDEO_003,
 /** 推理失败：工作流未产出可用视频。 */
 VIDEO_004,
 /** 超时：长时间未完成。 */
 VIDEO_005,
 /** 资产保存失败：生成成功但结果登记失败。 */
 VIDEO_006,
 /** 鉴权失败：内部令牌或所有者缺失。 */
 VIDEO_007,
 /** 幂等冲突：同一幂等键对应不同请求。 */
 VIDEO_008,
 /** 资源不存在：未找到或不属于当前账户。 */
 VIDEO_009
}
